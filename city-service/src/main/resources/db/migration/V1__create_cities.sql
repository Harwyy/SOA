CREATE TABLE cities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255) NOT NULL,
    coordinates_x BIGINT NOT NULL,
    coordinates_y REAL NOT NULL,
    creation_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    area REAL NOT NULL,
    population INTEGER NOT NULL,
    meters_above_sea_level DOUBLE,
    establishment_date TIMESTAMP(6),
    capital BOOLEAN NOT NULL,
    climate VARCHAR(32),
    governor_birthday TIMESTAMP(6),
    CONSTRAINT pk_cities PRIMARY KEY (id),
    CONSTRAINT ck_cities_id_positive CHECK (id > 0),
    CONSTRAINT ck_cities_name_not_blank CHECK (TRIM(name) <> ''),
    CONSTRAINT ck_cities_area_positive CHECK (area > 0),
    CONSTRAINT ck_cities_population_positive CHECK (population > 0),
    CONSTRAINT ck_cities_coordinates_y_max CHECK (coordinates_y <= 952)
);
